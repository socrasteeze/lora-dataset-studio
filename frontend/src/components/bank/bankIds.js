/**
 * Reading the id-list answer that ▶ Review and "Select all in filter" depend on.
 *
 * Both actions ask the grid endpoint for the ids of the WHOLE current filter
 * (`ids_only=1`) and get back `{ids: [...]}`. This module owns the one decision
 * that answer needs, which is not "is the list empty" but "did the server
 * actually answer the question at all".
 *
 * WHY THAT IS A DISTINCTION WORTH A MODULE. The two are not the same fact, and
 * treating them as one made the app state a falsehood with complete confidence.
 * Flask serves `frontend/dist` off disk, per request — so the moment a rebuilt
 * bundle is written, every browser picks it up, while the Python process keeps
 * running whatever code it was STARTED with. Update without restarting and you
 * get a new frontend talking to an old backend. An older backend does not know
 * the `ids_only` argument; Flask ignores unknown query args, so it cheerfully
 * returns an ordinary grid page — `{images, total, offset}`, with no `ids` key
 * at all.
 *
 * The old reader was `d.ids || []`. That turned "this server has never heard of
 * the question you asked" into "your filter matches no images", and the UI then
 * said so out loud: two toasts reporting zero — "Nothing to review — no image
 * matches the current filter" and "0 image(s) selected (whole filter, all
 * pages)" — directly beneath a counter reading **1,128 shown of 1,128**. Every
 * word on screen was generated by working code, and the only wrong thing was
 * that a missing key had been read as an empty answer. The user is then sent
 * hunting through filters that were never the problem, because nothing on
 * screen points at the actual cause.
 *
 * So: an ARRAY is an answer, and an empty array is a real, honest one — a filter
 * that genuinely matches nothing must still say so quietly. Anything that is not
 * an array is not an answer, and is refused loudly, naming the cause the user can
 * actually act on.
 */

/** The message shown when the server answers without an id list. Exported so the
 *  test pins the remedy, not just the fact that something was thrown. */
export const STALE_BACKEND_MESSAGE =
  'The server did not answer with a list of images — it is probably running an '
  + 'older version than this page. Restart LDS and try again.'

/**
 * Pull the id list out of an `ids_only=1` response.
 *
 * @param  {unknown} payload  the decoded JSON body
 * @return {number[]}         the ids, possibly empty (an empty filter is valid)
 * @throws {Error}            when the body carries no id list at all
 */
export function idsFromResponse(payload) {
  const ids = payload && payload.ids
  if (!Array.isArray(ids)) throw new Error(STALE_BACKEND_MESSAGE)
  return ids
}
